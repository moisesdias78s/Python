# Tipo de dado bool (Boolean)
# Ao questionar algo em um programa,
# Só existem duas respostas possíveis:
# Sim (True) ou não (False).
# Existe vários operadores para "questionar".
# Dentre eles o ==, que é um operador lógico que 
# questiona se um valor é igual a outro
print(20 == 19) # Não -> False (Falso)
print(20 == 20) # Sim -> True (Verdadeiro)
print(type(True)) #Usando type para saber o objeto que é bool
print(type(False))
print(type(10 == 10))
print(type(10 == 11))

#Boolean usado praticamente para questionar o programa algo.
