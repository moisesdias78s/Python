#Tipos int e float
#int -> Número inteiro
#O tipo int representa qualquer número
#Posito ou negativo. int sem sinal é considerado
#positivo
print(11) #int
print(-11) #int
print(0)

#float -> Número com ponto flutuante
#O tipo float representa qualquer número
#positvo ou negativo com ponto flutuante.
#float sem sinal é considerado positivo
print(1.1, 10.11)
print(0.0 -2.4)  #Se tem casa decimal é float

#A função type mostra o tipo que o Python
# inferiu ao valor.
print(type("Moisés"))  #type vai mostrar o objeto inserido.
print(type(2))
print(type(0.0,))

